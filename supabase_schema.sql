-- LUMINA | Esquema para Supabase (PostgreSQL)
-- Ejecutar completo en Supabase > SQL Editor > New query.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category_id bigint references public.categories(id) on delete set null,
  price numeric(10,2) not null check (price >= 0),
  old_price numeric(10,2) check (old_price is null or old_price >= price),
  color text,
  light text,
  tag text,
  stock boolean not null default true,
  description text,
  rating numeric(2,1) default 0,
  reviews integer not null default 0 check (reviews >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  order_code text not null unique,
  status text not null default 'pendiente' check (status in ('pendiente','confirmado','preparando','enviado','entregado','cancelado')),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  discount numeric(10,2) not null default 0 check (discount >= 0),
  shipping_cost numeric(10,2) not null default 0 check (shipping_cost >= 0),
  total numeric(10,2) not null check (total >= 0),
  customer_name text not null,
  phone text not null,
  address text not null,
  city text not null,
  region text not null,
  delivery_method text not null check (delivery_method in ('Domicilio','Recojo')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) not null check (line_total >= 0)
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category_id);
create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- Crear automáticamente el perfil al registrarse mediante Supabase Auth.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)));
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- RLS: activar protección en todas las tablas.
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.favorites enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.contact_messages enable row level security;

drop policy if exists "Perfiles visibles por su propietario" on public.profiles;
create policy "Perfiles visibles por su propietario" on public.profiles for select to authenticated using (auth.uid() = id);
drop policy if exists "Editar perfil propio" on public.profiles;
create policy "Editar perfil propio" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Categorías públicas" on public.categories;
create policy "Categorías públicas" on public.categories for select to anon, authenticated using (true);
drop policy if exists "Productos activos públicos" on public.products;
create policy "Productos activos públicos" on public.products for select to anon, authenticated using (active = true);

drop policy if exists "Ver favoritos propios" on public.favorites;
create policy "Ver favoritos propios" on public.favorites for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Agregar favoritos propios" on public.favorites;
create policy "Agregar favoritos propios" on public.favorites for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Eliminar favoritos propios" on public.favorites;
create policy "Eliminar favoritos propios" on public.favorites for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Ver pedidos propios" on public.orders;
create policy "Ver pedidos propios" on public.orders for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Crear pedidos propios" on public.orders;
create policy "Crear pedidos propios" on public.orders for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Ver detalles de pedidos propios" on public.order_items;
create policy "Ver detalles de pedidos propios" on public.order_items for select to authenticated using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));
drop policy if exists "Crear detalles de pedidos propios" on public.order_items;
create policy "Crear detalles de pedidos propios" on public.order_items for insert to authenticated with check (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

drop policy if exists "Enviar consultas" on public.contact_messages;
create policy "Enviar consultas" on public.contact_messages for insert to anon, authenticated with check (user_id is null or user_id = auth.uid());
drop policy if exists "Ver consultas propias" on public.contact_messages;
create policy "Ver consultas propias" on public.contact_messages for select to authenticated using (auth.uid() = user_id);

